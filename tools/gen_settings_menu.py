#!/usr/bin/env python3
"""Generate source/SettingsMenuData.mc (the on-watch "Customize" menu) from resources/settings/settings.xml.

Run from the repo root: python3 tools/gen_settings_menu.py
The menu structure (sections, short labels) lives in GROUPS below.
Only boolean and list settings are exposed on the watch; text and date entries stay in Garmin Connect.
"""
import xml.etree.ElementTree as ET

SRC = "resources/settings/settings.xml"
OUT = "source/SettingsMenuData.mc"

# section title -> [(setting key, short label), ...]
GROUPS = [
    ("Look", [
        ("theme_code", "Theme"),
        ("use_analog", "Analog face"),
        ("digital_style", "Digital size"),
        ("big_number_type", "Big number"),
        ("zero_leading_digital", "Leading zero"),
        ("big_num_stripes", "Number stripes"),
        ("ticks_style", "Ticks"),
        ("left_digital_info", "Info on left"),
    ]),
    ("Data fields", [
        ("comp12h", "Top"),
        ("comp2h", "Top right"),
        ("comp4h", "Bottom right"),
        ("comp6h", "Bottom"),
        ("comp8h", "Bottom left"),
        ("comp10h", "Top left"),
        ("compbart", "Top bar"),
        ("compbarb", "Bottom bar"),
        ("compgrapht", "Top graph"),
        ("compgraphb", "Bottom graph"),
    ]),
    ("Power & always-on", [
        ("power_save_mode", "Low refresh (1/min)"),
        ("always_on_second", "Always-on seconds"),
        ("always_on_heart", "Always-on heart"),
        ("always_on_style", "Always-on size"),
    ]),
    ("Units & formats", [
        ("date_format", "Date format"),
        ("force_date_english", "English date"),
        ("battery_format", "Battery shows"),
        ("barometer_unit", "Pressure unit"),
        ("utc_timezone", "2nd time zone"),
        ("utc_shift", "Zone +30 min"),
        ("minimal_data", "Full numbers (no K)"),
    ]),
]

# long option labels (string id -> short text) so they fit on the watch screen
SHORT_OPTIONS = {
    "theme_dcontrast": "Contrast dark",
    "theme_lcontrast": "Contrast light",
    "digital_style_xbig": "Extra big",
    "digital_style_big": "Big",
    "digital_style_medium": "Medium",
    "digital_style_small": "Small",
    "time_secondary": "Time (2nd zone)",
    "calories": "Active calories",
    "notification": "Notifications",
    "phonestatus": "Phone status",
    "groupnoti": "Alarms + notifs",
    "temperature": "Temp (watch)",
    "temperature_out": "Temp (outside)",
    "temperature_hl": "Temp high/low",
    "countdown": "Countdown",
    "wind": "Wind",
    "datef3": "dd.mm.yy",
    "datef31": "mm.dd.yy",
    "battery_format_1": "Percent",
    "battery_format_2": "Days left",
    "barometer_unit_0": "Pascal (Pa)",
    "barometer_unit_1": "inHg",
}


def lit(text):
    return '"%s"' % text.replace('"', '\\"')


def ref(text):
    text = text.strip()
    if text.startswith("@Strings."):
        sid = text[len("@Strings."):]
        if sid in SHORT_OPTIONS:
            return lit(SHORT_OPTIONS[sid])
        return "Rez.Strings." + sid
    return lit(text)


def value(text):
    text = text.strip()
    try:
        return str(int(text))
    except ValueError:
        return lit(text)


root = ET.parse(SRC).getroot()
by_key = {}
for s in root.iter("setting"):
    by_key[s.get("propertyKey").replace("@Properties.", "")] = s

option_sets = {}  # rendered options -> variable name
rendered_groups = []
used = set()
for title, items in GROUPS:
    entries = []
    for key, label in items:
        s = by_key[key]
        cfg = s.find("settingConfig")
        kind = cfg.get("type")
        used.add(key)
        if kind == "boolean":
            entries.append('["%s", %s, 0, null]' % (key, lit(label)))
        elif kind == "list":
            opts = "[" + ", ".join("[%s, %s]" % (value(e.get("value")), ref(e.text)) for e in cfg.findall("listEntry")) + "]"
            name = option_sets.setdefault(opts, "o%d" % len(option_sets))
            entries.append('["%s", %s, 1, %s]' % (key, lit(label), name))
        else:
            raise SystemExit("unsupported setting type for %s: %s" % (key, kind))
    rendered_groups.append((title, entries))

lines = [
    "// GENERATED by tools/gen_settings_menu.py from resources/settings/settings.xml - do not edit by hand.",
    "// Returns [[section title, [[property key, label, kind (0 = on/off, 1 = list), options [[value, label], ...]], ...]], ...]",
    "function settingsMenuData() {",
]
for opts, name in option_sets.items():
    lines.append("\tvar %s = %s;" % (name, opts))
lines.append("\treturn [")
for gi, (title, entries) in enumerate(rendered_groups):
    lines.append("\t\t[%s, [" % lit(title))
    for ei, e in enumerate(entries):
        lines.append("\t\t\t%s%s" % (e, "," if ei < len(entries) - 1 else ""))
    lines.append("\t\t]]%s" % ("," if gi < len(rendered_groups) - 1 else ""))
lines.append("\t];")
lines.append("}")
open(OUT, "w").write("\n".join(lines) + "\n")

missing = [k for k, s in by_key.items() if k not in used and s.find("settingConfig").get("type") in ("boolean", "list")]
print("wrote %s: %d settings in %d sections" % (OUT, len(used), len(GROUPS)))
if missing:
    print("not on the watch menu:", ", ".join(missing))
